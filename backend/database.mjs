import { AsyncLocalStorage } from "node:async_hooks";
import { DatabaseSync, backup } from "node:sqlite";
import { mkdir, open, chmod, rm } from "node:fs/promises";
import path from "node:path";
import { resolveDatabasePath } from "./services.mjs";

const COMMENT_TRANSACTION_LOCK = 721784230;
const SQLITE_SCHEMA = `
  CREATE TABLE IF NOT EXISTS comments (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    nickname TEXT NOT NULL,
    content TEXT NOT NULL,
    user_id TEXT,
    is_guest INTEGER NOT NULL DEFAULT 1,
    created_at INTEGER NOT NULL,
    expires_at INTEGER
  );`;
const POSTGRES_SCHEMA = `
  CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0 AND id <= 9007199254740991),
    nickname TEXT NOT NULL,
    content TEXT NOT NULL,
    user_id TEXT,
    is_guest INTEGER NOT NULL DEFAULT 1 CHECK (is_guest IN (0, 1)),
    created_at BIGINT NOT NULL CHECK (created_at BETWEEN 0 AND 9007199254740991),
    expires_at BIGINT CHECK (expires_at BETWEEN 0 AND 9007199254740991)
  );`;
const COMMENT_INDEXES = `
  CREATE INDEX IF NOT EXISTS idx_comments_created_at ON comments(created_at DESC);
  CREATE INDEX IF NOT EXISTS idx_comments_expiry ON comments(is_guest, expires_at);
  CREATE INDEX IF NOT EXISTS idx_comments_user ON comments(user_id);
  CREATE INDEX IF NOT EXISTS idx_comments_member_cursor ON comments(user_id, id DESC) WHERE is_guest = 0;
  CREATE INDEX IF NOT EXISTS idx_comments_member_recent ON comments(user_id, created_at DESC) WHERE is_guest = 0;
  CREATE INDEX IF NOT EXISTS idx_comments_guest_recent ON comments(created_at DESC) WHERE is_guest = 1;`;
const RATE_LIMIT_SCHEMA = `
  CREATE TABLE IF NOT EXISTS rate_limit_counters (
    prefix TEXT NOT NULL,
    key_hash TEXT NOT NULL,
    total_hits BIGINT NOT NULL CHECK (total_hits >= 0),
    reset_at BIGINT NOT NULL,
    PRIMARY KEY (prefix, key_hash)
  );
  CREATE INDEX IF NOT EXISTS idx_rate_limit_expiry ON rate_limit_counters(reset_at);`;
const SELECT_SNAPSHOT = "SELECT id, nickname, content, user_id, is_guest, created_at, expires_at FROM comments ORDER BY id";

// Only SQL authored by this application reaches this adapter. Keep question
// marks in quoted values, identifiers, dollar-quoted blocks and comments intact.
export function postgresPlaceholders(sql) {
  let output = "";
  let parameter = 0;
  let index = 0;
  while (index < sql.length) {
    const character = sql[index];
    if (character === "'" || character === '"') {
      const quote = character;
      const escape = quote === "'" && /(?:^|[^\w])e$/iu.test(sql.slice(0, index));
      output += sql[index++];
      while (index < sql.length) {
        const current = sql[index++];
        output += current;
        if (escape && current === "\\" && index < sql.length) output += sql[index++];
        else if (current === quote) {
          if (sql[index] === quote) output += sql[index++];
          else break;
        }
      }
    } else if (sql.startsWith("--", index)) {
      const end = sql.indexOf("\n", index);
      const stop = end === -1 ? sql.length : end + 1;
      output += sql.slice(index, stop);
      index = stop;
    } else if (sql.startsWith("/*", index)) {
      let depth = 1;
      output += "/*";
      index += 2;
      while (index < sql.length && depth) {
        if (sql.startsWith("/*", index)) { depth++; output += "/*"; index += 2; }
        else if (sql.startsWith("*/", index)) { depth--; output += "*/"; index += 2; }
        else output += sql[index++];
      }
    } else if (character === "$" && /^\$(?:[a-z_][a-z0-9_]*)?\$/iu.test(sql.slice(index))) {
      const delimiter = sql.slice(index).match(/^\$(?:[a-z_][a-z0-9_]*)?\$/iu)[0];
      const end = sql.indexOf(delimiter, index + delimiter.length);
      const stop = end === -1 ? sql.length : end + delimiter.length;
      output += sql.slice(index, stop);
      index = stop;
    } else {
      output += character === "?" ? `$${++parameter}` : character;
      index++;
    }
  }
  return output;
}

function safeInteger(value) {
  const number = Number(value);
  if (!Number.isSafeInteger(number)) throw new RangeError("Database integer exceeds the safe JavaScript range");
  return number;
}

function postgresRows(result) {
  const integerColumns = new Set((result.fields || []).filter(field => field.dataTypeID === 20).map(field => field.name));
  return result.rows.map(row => Object.fromEntries(Object.entries(row).map(([key, value]) =>
    [key, value !== null && integerColumns.has(key) ? safeInteger(value) : value])));
}

function postgresAccess(query, assertActive = () => {}) {
  return {
    prepare(sql) {
      const converted = postgresPlaceholders(sql);
      return {
        async all(...parameters) {
          assertActive();
          return postgresRows(await query(converted, parameters));
        },
        async get(...parameters) {
          assertActive();
          return postgresRows(await query(converted, parameters))[0];
        },
        async run(...parameters) {
          assertActive();
          // SQLite returns lastInsertRowid separately. PostgreSQL needs an
          // explicit RETURNING clause, including when restoring explicit IDs.
          const insert = /^\s*INSERT\s+INTO\s+(?:public\.)?comments\s*\(/iu.test(converted);
          const statement = insert && !/\bRETURNING\b/iu.test(converted)
            ? `${converted.replace(/;\s*$/u, "")} RETURNING id` : converted;
          const result = await query(statement, parameters);
          const rows = postgresRows(result);
          return { changes: result.rowCount || 0, lastInsertRowid: insert && rows[0]?.id !== undefined ? safeInteger(rows[0].id) : 0 };
        }
      };
    },
    async exec(sql) {
      assertActive();
      await query(sql);
    }
  };
}

async function reserveSnapshot(destination) {
  await mkdir(path.dirname(destination), { recursive: true, mode: 0o700 });
  const reservation = await open(destination, "wx", 0o600);
  await reservation.close();
}

async function sqliteSnapshot(destination, rows, highWater) {
  await reserveSnapshot(destination);
  let snapshot;
  try {
    snapshot = new DatabaseSync(destination);
    snapshot.exec(`${SQLITE_SCHEMA}${COMMENT_INDEXES} BEGIN IMMEDIATE;`);
    const insert = snapshot.prepare("INSERT INTO comments (id, nickname, content, user_id, is_guest, created_at, expires_at) VALUES (?, ?, ?, ?, ?, ?, ?)");
    for (const row of rows) insert.run(row.id, row.nickname, row.content, row.user_id, row.is_guest, row.created_at, row.expires_at);
    // IDs already issued and later deleted must stay unavailable after restore,
    // including when every comment has been deleted from the source database.
    snapshot.prepare("DELETE FROM sqlite_sequence WHERE name = ?").run("comments");
    // sqlite_sequence.seq has no INTEGER affinity: node:sqlite binds Numbers
    // as REAL, so cast explicitly for interoperable integer backup metadata.
    snapshot.prepare("INSERT INTO sqlite_sequence (name, seq) VALUES (?, CAST(? AS INTEGER))").run("comments", highWater);
    snapshot.exec("COMMIT");
    if (snapshot.prepare("PRAGMA quick_check").get().quick_check !== "ok") throw new Error("Backup integrity check failed");
    snapshot.close();
    snapshot = undefined;
    await chmod(destination, 0o600);
    return destination;
  } catch (error) {
    try { snapshot?.close(); } catch {}
    await rm(destination, { force: true });
    throw error;
  }
}

// Exported separately so pool ownership and transaction behaviour can be
// exercised without a production connection or secret.
export async function createPostgresDatabase(pool) {
  const context = new AsyncLocalStorage();
  const marker = {};
  const assertRoot = () => {
    if (context.getStore() === marker) throw new Error("Use the transaction-scoped database inside its callback");
  };
  // CREATE TABLE IF NOT EXISTS alone can race at cold starts. The same advisory
  // lock serializes schema setup and comment check-and-insert transactions.
  const initializer = await pool.connect();
  try {
    // This batch contains application constants only. One simple-protocol
    // message retains transaction order, replacing four network round trips with one.
    await initializer.query(`BEGIN;
      SELECT pg_advisory_xact_lock(${COMMENT_TRANSACTION_LOCK});
      ${POSTGRES_SCHEMA}${COMMENT_INDEXES}${RATE_LIMIT_SCHEMA}
      COMMIT;`);
  } catch (error) {
    try { await initializer.query("ROLLBACK"); } catch {}
    throw error;
  } finally { initializer.release(); }
  const access = postgresAccess((sql, parameters) => pool.query(sql, parameters), assertRoot);
  return {
    ...access,
    kind: "postgres",
    databasePath: null,
    async transaction(callback) {
      assertRoot();
      const client = await pool.connect();
      let active = true;
      const tx = postgresAccess((sql, parameters) => client.query(sql, parameters), () => {
        if (!active) throw new Error("Transaction is already closed");
      });
      try {
        // The lock ID is fixed in this module; request data stays parameterized
        // in tx.prepare(). Complete the lock acquisition before user work runs.
        await client.query(`BEGIN; SELECT pg_advisory_xact_lock(${COMMENT_TRANSACTION_LOCK});`);
        const value = await context.run(marker, () => callback(tx));
        active = false;
        await client.query("COMMIT");
        return value;
      } catch (error) {
        active = false;
        try { await client.query("ROLLBACK"); } catch {}
        throw error;
      } finally { client.release(); }
    },
    async snapshot(destination) {
      assertRoot();
      const client = await pool.connect();
      try {
        await client.query("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY");
        const rows = postgresRows(await client.query(SELECT_SNAPSHOT));
        const sequence = postgresRows(await client.query("SELECT pg_sequence_last_value(pg_get_serial_sequence('comments', 'id')::regclass) AS high_water"))[0];
        const highWater = Math.max(rows.at(-1)?.id || 0, safeInteger(sequence?.high_water ?? 0));
        await client.query("COMMIT");
        return await sqliteSnapshot(destination, rows, highWater);
      } catch (error) {
        try { await client.query("ROLLBACK"); } catch {}
        throw error;
      } finally { client.release(); }
    },
    async close() { assertRoot(); await pool.end(); }
  };
}

async function openSqliteDatabase(env, directory) {
  let databasePath;
  try { databasePath = resolveDatabasePath(env, directory); }
  catch (error) { error.code = "DATABASE_CONFIG"; throw error; }
  await mkdir(path.dirname(databasePath), { recursive: true });
  const database = new DatabaseSync(databasePath);
  try {
    database.exec(`PRAGMA journal_mode = WAL; PRAGMA synchronous = NORMAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000; ${SQLITE_SCHEMA}${COMMENT_INDEXES}`);
  } catch (error) { try { database.close(); } catch {} throw error; }
  let tail = Promise.resolve();
  const context = new AsyncLocalStorage();
  const marker = {};
  const enqueue = task => {
    if (context.getStore() === marker) return Promise.reject(new Error("Use the transaction-scoped database inside its callback"));
    const result = tail.then(task);
    tail = result.catch(() => {});
    return result;
  };
  const access = (schedule, assertActive = () => {}) => ({
    prepare(sql) {
      const execute = (method, parameters) => schedule(() => {
        assertActive();
        return database.prepare(sql)[method](...parameters);
      });
      return {
        all: (...parameters) => execute("all", parameters),
        get: (...parameters) => execute("get", parameters),
        run: (...parameters) => execute("run", parameters)
      };
    },
    exec: sql => schedule(() => { assertActive(); database.exec(sql); })
  });
  return {
    ...access(enqueue),
    kind: "sqlite",
    databasePath,
    transaction: callback => enqueue(async () => {
      database.exec("BEGIN IMMEDIATE");
      let active = true;
      const tx = access(async task => task(), () => { if (!active) throw new Error("Transaction is already closed"); });
      try {
        const value = await context.run(marker, () => callback(tx));
        active = false;
        database.exec("COMMIT");
        return value;
      } catch (error) {
        active = false;
        try { database.exec("ROLLBACK"); } catch {}
        throw error;
      }
    }),
    snapshot: destination => enqueue(async () => {
      if (path.resolve(databasePath) === path.resolve(destination)) throw new Error("Backup must not overwrite the source database");
      await reserveSnapshot(destination);
      try {
        await backup(database, destination);
        const check = new DatabaseSync(destination, { readOnly: true });
        try {
          if (check.prepare("PRAGMA quick_check").get().quick_check !== "ok") throw new Error("Backup integrity check failed");
        } finally { check.close(); }
        await chmod(destination, 0o600);
        return destination;
      } catch (error) { await rm(destination, { force: true }); throw error; }
    }),
    close: () => enqueue(() => { database.close(); })
  };
}

export async function openDatabase(env, directory) {
  const connectionString = String(env.DATABASE_URL ?? "").trim();
  if (!connectionString) {
    if (env.VERCEL === "1") throw Object.assign(new Error("Vercel requires DATABASE_URL for persistent comments and shared rate limits"), { code: "DATABASE_CONFIG" });
    return openSqliteDatabase(env, directory);
  }
  try {
    const url = new URL(connectionString);
    if (!["postgres:", "postgresql:"].includes(url.protocol) || !url.hostname) throw new Error();
  } catch {
    throw Object.assign(new Error("DATABASE_URL must be a PostgreSQL connection URL"), { code: "DATABASE_CONFIG" });
  }
  const { Pool } = await import("pg");
  const pool = new Pool({ connectionString, max: 3, idleTimeoutMillis: 10_000, connectionTimeoutMillis: 10_000, statement_timeout: 15_000, query_timeout: 20_000, allowExitOnIdle: true });
  if (env.VERCEL === "1") {
    const { attachDatabasePool } = await import("@vercel/functions");
    attachDatabasePool(pool);
  }
  // Idle pool errors must have a listener, but their messages can contain a
  // connection address. Log only the same sanitized metadata as API errors.
  pool.on("error", error => console.error("Database connection error", { name: error?.name, code: error?.code }));
  try { return await createPostgresDatabase(pool); }
  catch (error) { await pool.end().catch(() => {}); throw error; }
}
