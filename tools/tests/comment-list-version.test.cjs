const INSERT = "INSERT INTO comments (nickname, content, user_id, is_guest, created_at, expires_at) VALUES (?, ?, ?, ?, ?, ?)";

function pgliteHarness(engine) {
  const query = async (sql, parameters) => {
    if (!parameters?.length && sql.includes(";")) return (await engine.exec(sql)).at(-1);
    const result = await engine.query(sql, parameters);
    return { ...result, rowCount: result.affectedRows };
  };
  return { query, async connect() { return { query, release() {} }; }, async end() {} };
}

async function versionOf(db) {
  const { SELECT_COMMENT_LIST_VERSION } = await import("../../backend/database.mjs");
  return Number((await db.prepare(SELECT_COMMENT_LIST_VERSION).get()).version);
}

test("PostgreSQL list version migration is idempotent, keeps existing rows and bumps on every write", async () => {
  const { PGlite } = require("@electric-sql/pglite");
  const { createPostgresDatabase } = await import("../../backend/database.mjs");
  const engine = new PGlite();
  try {
    // A database created by an older deployment: comments exist, no counter yet.
    await engine.exec(`CREATE TABLE comments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nickname TEXT NOT NULL,
      content TEXT NOT NULL, user_id TEXT, is_guest INTEGER NOT NULL DEFAULT 1, created_at BIGINT NOT NULL, expires_at BIGINT);
      INSERT INTO comments (nickname, content, is_guest, created_at) VALUES ('old', 'kept', 1, 1);`);
    const first = await createPostgresDatabase(pgliteHarness(engine));
    assert.equal(await versionOf(first), 0);
    await first.transaction(tx => tx.prepare(INSERT).run("a", "posted", null, 1, 2, 999));
    assert.equal(await versionOf(first), 1);
    // A second cold start re-runs the batch without resetting or duplicating anything.
    const second = await createPostgresDatabase(pgliteHarness(engine));
    assert.equal(await versionOf(second), 1);
    const triggers = await engine.query("SELECT count(*)::int AS n FROM pg_trigger WHERE tgname = 'comments_list_version'");
    assert.equal(triggers.rows[0].n, 1);
    assert.equal((await engine.query("SELECT count(*)::int AS n FROM comment_list_version")).rows[0].n, 1);
    await second.prepare("UPDATE comments SET nickname = ? WHERE content = ?").run("b", "posted");
    assert.equal(await versionOf(second), 2);
    await second.prepare("DELETE FROM comments WHERE expires_at <= ?").run(1000); // expiry cleanup
    assert.equal(await versionOf(second), 3);
    await second.prepare("DELETE FROM comments WHERE id = ?").run(987654); // no row: no change
    assert.equal(await versionOf(second), 3);
    await assert.rejects(second.transaction(async tx => {
      await tx.prepare(INSERT).run("c", "rolled back", null, 1, 3, null);
      throw new Error("abort");
    }));
    assert.equal(await versionOf(second), 3, "a rolled-back write never publishes a version");
    assert.equal((await engine.query("SELECT content FROM comments")).rows.map(row => row.content).join(), "kept");
  } finally { await engine.close(); }
});

test("SQLite list version migration is idempotent and bumps on insert, update and delete", async () => {
  const { openDatabase } = await import("../../backend/database.mjs");
  const directory = await mkdtemp(path.join(tmpdir(), "comment-version-"));
  const env = { COMMENTS_DB_PATH: path.join(directory, "comments.db") };
  try {
    let db = await openDatabase(env, directory);
    assert.equal(await versionOf(db), 0);
    await db.transaction(tx => tx.prepare(INSERT).run("a", "one", null, 1, 1, null));
    await db.prepare("UPDATE comments SET content = ? WHERE content = ?").run("two", "one");
    await db.prepare("DELETE FROM comments WHERE content = ?").run("two");
    assert.equal(await versionOf(db), 3);
    await db.close();
    db = await openDatabase(env, directory);
    assert.equal(await versionOf(db), 3, "reopening keeps the counter");
    await db.close();
  } finally { await rm(directory, { recursive: true, force: true }); }
});

test("a warm cache checks the shared version and refetches after another instance writes", async () => {
  const { createPublicCommentsCache } = await import("../../backend/public-comments-cache.mjs");
  let version = 5, calls = 0, now = 1000;
  const rows = [[{ id: 1, nickname: "a", content: "x", is_guest: 0, created_at: 1, expires_at: null }], []];
  const cache = createPublicCommentsCache({ now: () => now, version: async () => String(version), load: async () => rows[Math.min(calls++, 1)] });
  assert.equal((await cache.read()).length, 1);
  now = 2000;
  assert.equal((await cache.read()).length, 1);
  assert.equal(calls, 1, "unchanged version serves memory");
  version = 6; // a deletion committed elsewhere
  assert.equal((await cache.read()).length, 0);
  assert.equal(calls, 2);
});

test("a failed version probe keeps the bounded snapshot instead of failing the read", async () => {
  const { createPublicCommentsCache } = await import("../../backend/public-comments-cache.mjs");
  let fail = false, calls = 0, now = 1000;
  const cache = createPublicCommentsCache({ now: () => now, version: async () => { if (fail) throw new Error("db"); return 1; }, load: async () => { calls++; return []; } });
  await cache.read();
  fail = true; now = 20_000;
  assert.deepEqual(await cache.read(), []);
  assert.equal(calls, 1);
  now = 31_001;
  await assert.rejects(cache.read());
});

function fakeResponse(statusCode = 200) {
  const headers = new Map([["ratelimit", "limit=120, remaining=119"], ["ratelimit-policy", "120;w=60"]]);
  return {
    statusCode, headers,
    setHeader(name, value) { headers.set(name.toLowerCase(), value); },
    removeHeader(name) { headers.delete(name.toLowerCase()); },
    vary(name) { const current = headers.get("vary"); headers.set("vary", current ? `${current}, ${name}` : name); }
  };
}

test("only credential-free list reads become CDN-cacheable and every variant varies on Origin", async () => {
  const { applyPublicCommentsCacheHeaders } = await import("../../backend/public-comments-cache.mjs");
  const anonymous = fakeResponse();
  assert.equal(applyPublicCommentsCacheHeaders({ headers: { origin: "https://osagechan.top" } }, anonymous), true);
  assert.equal(anonymous.headers.get("cache-control"), "public, max-age=0, s-maxage=30, stale-while-revalidate=30");
  assert.equal(anonymous.headers.get("vercel-cache-tag"), "public-comments");
  assert.match(anonymous.headers.get("vary"), /Origin/);
  assert.doesNotMatch(anonymous.headers.get("vary"), /Cookie/, "Vercel never stores Vary: Cookie responses");
  assert.ok(!anonymous.headers.has("ratelimit") && !anonymous.headers.has("ratelimit-policy"), "per-client counters are not shared");
  for (const headers of [{ authorization: "Bearer token" }, { cookie: "sAccessToken=x" }, { "st-auth-mode": "header" }, { rid: "session" }]) {
    const res = fakeResponse();
    assert.equal(applyPublicCommentsCacheHeaders({ headers: { origin: "https://osagechan.top", ...headers } }, res), false);
    assert.equal(res.headers.get("cache-control"), "no-store");
    assert.ok(!res.headers.has("vercel-cache-tag"));
    assert.match(res.headers.get("vary"), /Origin/);
  }
  const failed = fakeResponse(503);
  assert.equal(applyPublicCommentsCacheHeaders({ headers: {} }, failed), false);
  assert.equal(failed.headers.get("cache-control"), "no-store");
});

